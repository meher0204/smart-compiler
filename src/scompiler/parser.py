"""parser.py - Recursive-descent parser with error detection and recovery.

Parses token streams generated by the lexer into grammar constructs defined by the
language specification, recovering gracefully from errors to continue parsing.
"""

from __future__ import annotations

from typing import Any, List, Optional

from scompiler.diagnostics import DiagnosticCollector
from scompiler.lexer import tokenize
from scompiler.recovery import (
    BLOCK_SYNC,
    EXPR_SYNC,
    RecoveryManager,
)
from scompiler.report import ErrorReport
from scompiler.suggest import suggest
from scompiler.tokens import Token, TokenType


class ParseError(Exception):
    def __init__(self, message: str, token: Token, expected: Optional[str] = None):
        self.message = message
        self.token = token
        self.expected = expected
        super().__init__(message)


class Parser:
    """Recursive-descent parser with full error recovery and diagnostic collection."""

    def __init__(
        self,
        tokens: List[Token],
        source: str = "",
        collector: Optional[DiagnosticCollector] = None,
    ) -> None:
        self.tokens = tokens
        self.source = source
        self.pos = 0
        self.collector = collector if collector is not None else DiagnosticCollector()
        self.recovery = RecoveryManager(self)
        self.errors: List[str] = []

    def current(self) -> Token:
        if self.pos >= len(self.tokens):
            return self.tokens[-1] if self.tokens else Token(TokenType.EOF, "", 1, 1)
        return self.tokens[self.pos]

    def peek(self, offset: int = 1) -> Token:
        index = self.pos + offset
        if index >= len(self.tokens):
            return self.tokens[-1] if self.tokens else Token(TokenType.EOF, "", 1, 1)
        return self.tokens[index]

    def prev(self) -> Optional[Token]:
        if self.pos > 0 and self.pos - 1 < len(self.tokens):
            return self.tokens[self.pos - 1]
        return None

    def check(self, *types: TokenType) -> bool:
        return self.current().type in types

    def advance(self) -> Token:
        token = self.current()
        if token.type != TokenType.EOF:
            self.pos += 1
        return token

    def match(self, *types: TokenType) -> Optional[Token]:
        if self.check(*types):
            return self.advance()
        return None

    def expect(self, token_type: TokenType) -> Token:
        if self.check(token_type):
            return self.advance()

        token = self.current()
        expected = token_type.value
        found = token.lexeme if token.type != TokenType.EOF else "EOF"
        raise ParseError(
            f"Line {token.line}, column {token.col}: expected {expected}, found {found}",
            token,
            expected=expected,
        )

    def expect_any(self, *types: TokenType) -> Token:
        if self.check(*types):
            return self.advance()
        token = self.current()
        expected = " or ".join(t.value for t in types)
        found = token.lexeme if token.type != TokenType.EOF else "EOF"
        raise ParseError(
            f"Line {token.line}, column {token.col}: expected {expected}, found {found}",
            token,
            expected=expected,
        )

    def expect_semicolon(self) -> Optional[Token]:
        """Expect a semicolon, using phrase-level virtual insertion when safe."""
        if self.check(TokenType.SEMICOLON):
            return self.advance()

        prev_tok = self.prev()
        if self.recovery.try_recover_missing_semicolon(prev_tok):
            return None

        # Semicolon missing and unsafe to virtually insert -> trigger error & panic
        curr = self.current()
        found = curr.lexeme if curr.type != TokenType.EOF else "EOF"
        msg = f"Line {curr.line}, column {curr.col}: expected ';', found {found}"
        if self.recovery.should_report_error(self.pos):
            self.collector.add_syntax_error(
                code="MISSING_SEMICOLON",
                message=msg,
                line=curr.line,
                column=curr.col,
                lexeme=found,
                expected=";",
                suggestion="Insert ';' after the previous statement.",
                recovery_info="Skipped invalid tokens until the next statement boundary.",
            )
        self.recovery.synchronize_statement()
        return None

    def expect_rparen(
        self, open_paren: Optional[Token] = None, context: str = "expression"
    ) -> Optional[Token]:
        """Expect a closing parenthesis ')', using phrase-level virtual insertion when safe."""
        if self.check(TokenType.RPAREN):
            return self.advance()

        if self.recovery.try_recover_missing_rparen(open_paren, context=context):
            return None

        curr = self.current()
        found = curr.lexeme if curr.type != TokenType.EOF else "EOF"
        msg = f"Line {curr.line}, column {curr.col}: expected ')', found {found}"
        if self.recovery.should_report_error(self.pos):
            self.collector.add_syntax_error(
                code="MISSING_RPAREN",
                message=msg,
                line=curr.line,
                column=curr.col,
                lexeme=found,
                expected=")",
                suggestion="Insert ')' to close the condition."
                if "condition" in context
                else "Insert ')'.",
                recovery_info=(
                    "Skipped invalid tokens until the next expression/statement boundary."
                ),
                related=(open_paren.line, open_paren.col) if open_paren else None,
            )
        self.recovery.synchronize_to(EXPR_SYNC)
        return None

    def expect_rbrace(self, open_brace: Optional[Token] = None) -> Optional[Token]:
        """Expect a closing brace '}', using phrase-level virtual insertion when safe."""
        if self.check(TokenType.RBRACE):
            return self.advance()

        if self.recovery.try_recover_missing_rbrace(open_brace):
            return None

        curr = self.current()
        found = curr.lexeme if curr.type != TokenType.EOF else "EOF"
        msg = f"Line {curr.line}, column {curr.col}: expected '}}', found {found}"
        if self.recovery.should_report_error(self.pos):
            self.collector.add_syntax_error(
                code="MISSING_RBRACE",
                message=msg,
                line=curr.line,
                column=curr.col,
                lexeme=found,
                expected="}",
                suggestion="Insert '}' to close the block.",
                recovery_info="Skipped invalid tokens until the block boundary.",
                related=(open_brace.line, open_brace.col) if open_brace else None,
            )
        self.recovery.synchronize_to(BLOCK_SYNC)
        return None

    # ---- Grammar Rules ----------------------------------------------------

    def parse(self) -> bool:
        self.program()
        if not self.check(TokenType.EOF):
            curr = self.current()
            found = curr.lexeme if curr.type != TokenType.EOF else "EOF"
            if self.recovery.should_report_error(self.pos):
                self.collector.add_syntax_error(
                    code="UNEXPECTED_TOKEN",
                    message=f"Line {curr.line}, column {curr.col}: expected EOF, found {found}",
                    line=curr.line,
                    column=curr.col,
                    lexeme=found,
                    expected="EOF",
                )
        self.collector.apply_suggestions(suggest)
        self.errors = [d.message for d in self.collector.errors]
        return not self.collector.has_errors

    # Program -> DeclarationList
    def program(self) -> None:
        while not self.check(TokenType.EOF):
            old_pos = self.pos
            try:
                self.declaration()
            except ParseError as error:
                if self.recovery.should_report_error(error.token.col):
                    self.collector.add_syntax_error(
                        code="SYNTAX_ERROR",
                        message=error.message,
                        line=error.token.line,
                        column=error.token.col,
                        lexeme=error.token.lexeme if error.token.type != TokenType.EOF else "EOF",
                        expected=error.expected,
                        recovery_info="Skipped invalid tokens to resume at next declaration.",
                    )
                self.recovery.synchronize_statement()

            if self.pos == old_pos and not self.check(TokenType.EOF):
                self.advance()

    def declaration(self) -> None:
        if self.check(TokenType.INT, TokenType.FLOAT):
            self.advance()
            self.expect(TokenType.ID)

            if self.match(TokenType.LPAREN):
                self.param_list()
                self.expect_rparen(context="parameter list")
                self.block()
            else:
                if self.match(TokenType.ASSIGN):
                    self.expr()
                self.expect_semicolon()
        else:
            token = self.current()
            found = token.lexeme if token.type != TokenType.EOF else "EOF"
            raise ParseError(
                f"Line {token.line}, column {token.col}: "
                f"expected declaration or function, found {found}",
                token,
            )

    def param_list(self) -> None:
        if self.check(TokenType.INT, TokenType.FLOAT):
            self.param()
            while self.match(TokenType.COMMA):
                self.param()

    def param(self) -> None:
        self.expect_any(TokenType.INT, TokenType.FLOAT)
        self.expect(TokenType.ID)

    def statement(self) -> None:
        if self.check(TokenType.INT, TokenType.FLOAT):
            self.declaration()
        elif self.check(TokenType.ID):
            if (
                self.pos + 1 < len(self.tokens)
                and self.tokens[self.pos + 1].type == TokenType.ASSIGN
            ):
                self.assignment()
            else:
                self.expr()
                self.expect_semicolon()
        elif self.match(TokenType.IF):
            open_paren = self.expect(TokenType.LPAREN)
            self.expr()
            self.expect_rparen(open_paren=open_paren, context="if condition")
            self.statement()
            if self.match(TokenType.ELSE):
                self.statement()
        elif self.match(TokenType.WHILE):
            open_paren = self.expect(TokenType.LPAREN)
            self.expr()
            self.expect_rparen(open_paren=open_paren, context="while condition")
            self.statement()
        elif self.match(TokenType.RETURN):
            if not self.check(TokenType.SEMICOLON):
                self.expr()
            self.expect_semicolon()
        elif self.match(TokenType.PRINTF):
            open_paren = self.expect(TokenType.LPAREN)
            self.expr()
            self.expect_rparen(open_paren=open_paren, context="printf argument")
            self.expect_semicolon()
        elif self.check(TokenType.LBRACE):
            self.block()
        else:
            self.expr()
            self.expect_semicolon()

    def assignment(self) -> None:
        self.expect(TokenType.ID)
        self.expect(TokenType.ASSIGN)
        self.expr()
        self.expect_semicolon()

    def block(self) -> None:
        open_brace = self.expect(TokenType.LBRACE)
        while not self.check(TokenType.RBRACE, TokenType.EOF):
            old_pos = self.pos
            try:
                self.statement()
            except ParseError as error:
                if self.recovery.should_report_error(error.token.col):
                    self.collector.add_syntax_error(
                        code="SYNTAX_ERROR",
                        message=error.message,
                        line=error.token.line,
                        column=error.token.col,
                        lexeme=error.token.lexeme if error.token.type != TokenType.EOF else "EOF",
                        expected=error.expected,
                        recovery_info="Continued parsing from next statement.",
                    )
                self.recovery.synchronize_statement()

            if self.pos == old_pos and not self.check(TokenType.RBRACE, TokenType.EOF):
                self.advance()

        self.expect_rbrace(open_brace=open_brace)

    def expr(self) -> None:
        self.add_expr()
        if self.match(
            TokenType.LT, TokenType.GT, TokenType.LE, TokenType.GE, TokenType.EQ, TokenType.NE
        ):
            self.add_expr()

    def add_expr(self) -> None:
        self.mul_expr()
        while self.match(TokenType.PLUS, TokenType.MINUS):
            self.mul_expr()

    def mul_expr(self) -> None:
        self.unary_expr()
        while self.match(TokenType.STAR, TokenType.SLASH, TokenType.PERCENT):
            self.unary_expr()

    def unary_expr(self) -> None:
        if self.match(TokenType.PLUS, TokenType.MINUS):
            self.unary_expr()
        else:
            self.primary()

    def primary(self) -> None:
        if self.match(TokenType.ID):
            if self.match(TokenType.LPAREN):
                self.arg_list()
                self.expect_rparen(context="function call arguments")
        elif self.match(TokenType.INT_LITERAL, TokenType.FLOAT_LITERAL):
            pass
        elif self.match(TokenType.LPAREN):
            open_paren = self.prev()
            self.expr()
            self.expect_rparen(open_paren=open_paren, context="expression")
        else:
            token = self.current()
            found = token.lexeme if token.type != TokenType.EOF else "EOF"
            raise ParseError(
                f"Line {token.line}, column {token.col}: expected expression, found {found}",
                token,
                expected="expression",
            )

    def arg_list(self) -> None:
        if not self.check(TokenType.RPAREN, TokenType.EOF):
            self.expr()
            while self.match(TokenType.COMMA):
                self.expr()

    def synchronize(self) -> None:
        """Legacy synchronization helper delegating to RecoveryManager."""
        self.recovery.synchronize_statement()


class ParseResult(dict):
    """Dictionary-compatible compilation result with attribute access and error reporting."""

    def __init__(
        self,
        success: bool,
        errors: List[str],
        collector: DiagnosticCollector,
        source: str = "",
    ):
        report_str = ErrorReport(collector, source=source).render()
        super().__init__(
            success=success,
            errors=errors,
            diagnostics=collector.sorted(),
            collector=collector,
            report=report_str,
        )
        self._collector = collector
        self._source = source
        self._report_str = report_str

    @property
    def success(self) -> bool:
        return self["success"]

    @property
    def errors(self) -> List[str]:
        return self["errors"]

    @property
    def diagnostics(self) -> List[Any]:
        return self["diagnostics"]

    @property
    def report(self) -> str:
        return self._report_str

    def get_report(self, color: bool = False, show_source: bool = False) -> str:
        return ErrorReport(
            self._collector, source=self._source, color=color, show_source=show_source
        ).render()


def parse_source(source: str, max_errors: int = 50) -> ParseResult:
    """Full compilation front-end pipeline:

    Source Code -> Lexer -> Parser + Recovery -> Suggestions -> ErrorReport
    """
    tokens, lexical_errors = tokenize(source)
    collector = DiagnosticCollector(max_errors=max_errors)

    for lex_err in lexical_errors:
        collector.add_lexical_error(
            message=lex_err.message,
            line=lex_err.line,
            column=lex_err.col,
            lexeme=lex_err.lexeme,
        )

    parser = Parser(tokens, source=source, collector=collector)
    try:
        parser.parse()
    except ParseError as error:
        if parser.recovery.should_report_error(error.token.col):
            collector.add_syntax_error(
                code="SYNTAX_ERROR",
                message=error.message,
                line=error.token.line,
                column=error.token.col,
                lexeme=error.token.lexeme if error.token.type != TokenType.EOF else "EOF",
                expected=error.expected,
            )

    collector.apply_suggestions(suggest)

    all_error_messages = [d.message for d in collector.errors]
    is_success = not collector.has_errors

    return ParseResult(
        success=is_success,
        errors=all_error_messages,
        collector=collector,
        source=source,
    )
